"""Device measurements API (CC2026 Cloud Computing project).

    GET /health                 liveness information used by Azure and CI/CD
    GET /api/data               all measurements (optional ?device_id= filter)
    GET /api/data/{device_id}   measurements of one device (404 if unknown)
    GET /api/devices            sorted list of device IDs
    GET /api/stats              per-device averages
    GET /docs                   OpenAPI documentation generated by FastAPI
"""

from datetime import datetime, timezone
from statistics import fmean
from typing import Annotated

from fastapi import Depends, FastAPI, HTTPException, Path, Query
from fastapi.middleware.cors import CORSMiddleware

from .config import get_settings
from .data import MeasurementSource, get_measurement_source
from .models import DEVICE_ID_PATTERN, DeviceStats, Health, Measurement

settings = get_settings()

app = FastAPI(
    title="CC2026 Device Measurements API",
    version=settings.app_version,
    description="Serves device measurements as JSON.",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.cors_origins,
    allow_methods=["GET"],
    allow_headers=["*"],
)

Source = Annotated[MeasurementSource, Depends(get_measurement_source)]


@app.get("/", include_in_schema=False)
def root() -> dict[str, str]:
    return {"service": settings.app_name, "docs": "/docs", "data": "/api/data"}


@app.get("/health", response_model=Health, tags=["health"])
def health() -> Health:
    return Health(
        status="ok",
        service=settings.app_name,
        version=settings.app_version,
        timestamp=datetime.now(timezone.utc),
    )


@app.get("/api/data", response_model=list[Measurement], tags=["data"])
def list_measurements(
    source: Source,
    device_id: Annotated[str | None, Query(pattern=DEVICE_ID_PATTERN, description="Optional device filter")] = None,
) -> list[Measurement]:
    measurements = source.list_measurements()
    if device_id is None:
        return measurements
    return [m for m in measurements if m.device_id == device_id]


@app.get("/api/devices", response_model=list[str], tags=["data"])
def list_devices(source: Source) -> list[str]:
    return sorted({m.device_id for m in source.list_measurements()})


@app.get("/api/stats", response_model=list[DeviceStats], tags=["data"])
def device_stats(source: Source) -> list[DeviceStats]:
    by_device: dict[str, list[Measurement]] = {}
    for m in source.list_measurements():
        by_device.setdefault(m.device_id, []).append(m)
    return [
        DeviceStats(
            device_id=device_id,
            readings=len(readings),
            avg_temperature=round(fmean(m.temperature for m in readings), 2),
            avg_humidity=round(fmean(m.humidity for m in readings), 2),
        )
        for device_id, readings in sorted(by_device.items())
    ]


@app.get("/api/data/{device_id}", response_model=list[Measurement], tags=["data"])
def device_measurements(
    source: Source,
    device_id: Annotated[str, Path(pattern=DEVICE_ID_PATTERN, description="Device identifier, e.g. device-001")],
) -> list[Measurement]:
    measurements = [m for m in source.list_measurements() if m.device_id == device_id]
    if not measurements:
        raise HTTPException(status_code=404, detail=f"Device '{device_id}' not found")
    return measurements
